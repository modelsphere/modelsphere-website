import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
export async function generateTokens(root = process.cwd()): Promise<void> {
  const tokens = JSON.parse(
    await readFile(path.join(root, 'design/tokens.json'), 'utf8'),
  ) as {
    shared: Record<string, string>;
    light: Record<string, string>;
    dark: Record<string, string>;
  };
  const block = (v: Record<string, string>) =>
    Object.entries(v)
      .map(([k, value]) => `  --${k}: ${value};`)
      .join('\n');
  const output = `/* Generated by scripts/generate-tokens.ts. Edit design/tokens.json. */\n:root {\n${block(tokens.shared)}\n}\n:root, :root[data-theme='light'] {\n${block(tokens.light)}\n  color-scheme: light;\n}\n:root[data-theme='dark'] {\n${block(tokens.dark)}\n  color-scheme: dark;\n}\n@media (prefers-color-scheme: dark) {\n  html:not([data-theme-choice]) {\n${block(tokens.dark)}\n    color-scheme: dark;\n  }\n}\n`;
  await writeFile(path.join(root, 'src/css/tokens.css'), output);
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  await generateTokens();
